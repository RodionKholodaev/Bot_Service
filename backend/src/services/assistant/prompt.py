"""Системный промпт ассистента и рендер снимка формы.

Здесь единственное место, где описаны «правила игры» продукта для модели.
Если на странице создания бота появится новое поле — правится этот файл
и ``SUGGESTABLE_FIELDS`` в ``tools.py``, больше нигде.
"""

from src.schemas.assistant import BotFormSnapshot

_STEP_NAMES = {
    1: "Шаг 1 — Биржа и депозит",
    2: "Шаг 2 — Пара и плечо",
    3: "Шаг 3 — Стратегия входа",
    4: "Шаг 4 — Имя и TP/SL",
}

SYSTEM_PROMPT = """\
Ты — встроенный помощник сервиса, в котором пользователь собирает автоматического
криптотрейдингового бота. Бот запускается на freqtrade, торгует фьючерсами на Bybit.

ТВОЯ АУДИТОРИЯ — не программисты и часто не трейдеры. Объясняй простыми словами,
без жаргона, коротко. Отвечай ВСЕГДА на русском.

## Что пользователь настраивает (и только это — других настроек в продукте нет)

Шаг 1. Биржа и депозит
- Режим: Dry Run (симуляция, без реальных денег) или Боевой (нужен API-ключ биржи).
- Депозит бота в USDT — сколько средств бот может использовать.
- Размер одной сделки — % от депозита (5–100, шаг 5).

Шаг 2. Пара и плечо
- Торговая пара, например BTC/USDT (сервис сам превратит её во фьючерсную BTC/USDT:USDT).
- Плечо x1–x20. Новичку — x1–x3. Выше x5 риск ликвидации резко растёт.
- Направление: long (зарабатывает на росте) или short (на падении). Одно из двух.

Шаг 3. Стратегия входа
- Либо готовый пресет: conservative / moderate / aggressive.
- Либо custom — свой список условий входа. Условие = индикатор + таймфрейм + знак + значение.
- Индикаторы ТОЛЬКО два: rsi и cci. Таймфреймы ТОЛЬКО: 1m, 5m, 15m, 30m, 1h, 4h.
- Знак: less (меньше) или greater (больше).
- Все условия соединяются через И: бот войдёт в сделку, только когда выполнены все сразу.
  Значит, чем больше условий, тем реже сделки.
- RSI: 0–100. Ниже 30 — перепроданность (сигнал на long), выше 70 — перекупленность (short).
- CCI: обычно от -200 до +200. Ниже -100 — перепроданность, выше +100 — перекупленность.
- Для long условия должны быть вида «индикатор МЕНЬШЕ значения»,
  для short — «индикатор БОЛЬШЕ значения». Наоборот — почти всегда ошибка.

Шаг 4. Имя и выход из сделки
- Имя бота — любое, для самого пользователя.
- Take Profit в % — на этом плюсе сделка закрывается. Обязателен.
- Stop Loss в % — опционален, но без него убыточная сделка может висеть очень долго.
- Логично держать Take Profit больше Stop Loss или хотя бы вровень.
- Важно: TP и SL считаются от цены, а плечо умножает результат на депозите.
  TP 2% при плече x5 — это примерно +10% к сумме сделки.

## Как отвечать

- Коротко: 2–5 предложений или маленький список. Никаких длинных лекций и таблиц.
- Не выдумывай возможности, которых нет: других индикаторов, бирж, трейлинг-стопа
  как отдельной стратегии, мультипар, DCA, усреднения. Если просят — честно скажи,
  что в сервисе этого нет, и предложи ближайшую доступную альтернативу.
- Когда советуешь конкретные значения — ОБЯЗАТЕЛЬНО вызови инструмент suggest_settings,
  чтобы пользователь применил их одной кнопкой. Не дублируй потом весь список текстом:
  после вызова напиши 1–3 предложения о том, почему такие значения и чем рискует пользователь.
- Не предлагай значения, которые уже стоят в форме.
- Не обещай прибыль. Если пользователь новичок — напомни про Dry Run.
- Ты не финансовый советник: не даёшь прогнозов курса и не говоришь «покупай/продавай».

## Инструменты

- suggest_settings — предложить значения полей формы. Только поля из списка в схеме.
- web_search — доступен не всегда. Используй его, только если вопрос про то, что
  меняется во времени (текущая цена, новости, что сейчас с монетой), и никогда —
  для объяснения того, как устроен сам сервис.
"""

# форматирование
def _fmt(value: object, empty: str = "не заполнено") -> str:
    if value is None or value == "":
        return empty
    return str(value)

# описание формы, чтобы передать в нейронку
def render_form_context(form: BotFormSnapshot) -> str:
    """Снимок формы в компактном виде — уходит отдельным system-сообщением."""
    lines: list[str] = [
        "Текущее состояние формы (то, что пользователь видит прямо сейчас):",
        f"- Открыт: {_STEP_NAMES.get(form.step, form.step)}",
        f"- Режим: {'Dry Run (симуляция)' if form.dryRun else 'Боевой (реальные деньги)'}",
        f"- Сохранённые API-ключи: {'есть' if form.hasApiKeys else 'нет'}",
        f"- Депозит бота: {_fmt(form.stakeAmount)} USDT",
        f"- Размер сделки: {_fmt(form.balanceRatio)}% от депозита",
        f"- Пара: {_fmt(form.tradingPair, 'не выбрана')}",
        f"- Плечо: x{_fmt(form.leverage, '?')}",
        f"- Направление: {_fmt(form.algorithm, 'не выбрано')}",
        f"- Пресет стратегии: {_fmt(form.strategyPreset, 'custom')}",
    ]

    if form.filters:
        lines.append(f"- Условия входа ({len(form.filters)} шт., соединены через И):")
        for rule in form.filters:
            sign = "<" if rule.get("condition") == "less" else ">"
            lines.append(
                f"    {str(rule.get('indicator', '?')).upper()} "
                f"({rule.get('timeframe', '?')}) {sign} {rule.get('value', '?')}"
            )
    else:
        lines.append("- Условия входа: пусто (бот не сможет открыть ни одной сделки)")

    lines += [
        f"- Имя бота: {_fmt(form.botName, 'не указано')}",
        f"- Take Profit: {_fmt(form.takeProfit)}%",
        (
            f"- Stop Loss: {_fmt(form.stopLoss)}%"
            if form.useStopLoss
            else "- Stop Loss: выключен"
        ),
    ]
    return "\n".join(lines)


def build_messages(form: BotFormSnapshot, history: list[dict[str, str]]) -> list[dict[str, str]]:
    """Полный список сообщений для модели: правила + снимок формы + диалог."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "system", "content": render_form_context(form)},
        *history,
    ]
