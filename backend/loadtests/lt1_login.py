"""
LT-1: потолок RPS на POST /auth/login.

Что проверяем. Логин делает две вещи: SELECT по email (микросекунды) и
bcrypt.checkpw (~200 мс чистого CPU). Второе — синхронный вызов прямо в event loop
(src/core/security.py:17), то есть выполняется строго по одному запросу за раз,
сколько бы клиентов ни пришло. Система ведёт себя как очередь с одним обслуживающим
прибором, и у этого есть измеримая подпись:

  * ниже потолка: растёт число клиентов -> растёт RPS, латентность стоит;
  * выше потолка: растёт число клиентов -> RPS упирается в полку, а латентность
    растёт линейно, потому что вся добавка уходит в ожидание очереди.

Излом ищется сравнением нескольких уровней нагрузки: 1, 2, 5, 10, 20 клиентов.
Уровень задаётся при запуске (-u в консоли или поле в веб-интерфейсе), по одному
прогону на уровень — см. README.

Два решения, которые выглядят как небрежность, но сделаны намеренно:

  * логинимся ОДНИМ И ТЕМ ЖЕ пользователем — мы изолируем стоимость bcrypt,
    а разные пользователи добавили бы в замер разброс по SELECT и кэшу SQLite;
  * wait_time = 0 — паузы имитируют живого человека, но здесь мы ищем потолок
    сервиса, и любая пауза измеряет уже нас самих, а не его.

Пользователя готовит loadtests/seed_user.py — он же проверяет, что логин
отвечает 200. Ответ != 200 здесь считается провалом: с чужим email
verify_password не вызывается вовсе (короткое замыкание в AuthService.login),
запрос дешевеет на два порядка, и тест бодро отрапортует сотни RPS, померив пустоту.

Запуск — см. loadtests/README.md
"""

import os

from locust import HttpUser, constant, task

EMAIL = os.getenv("LT_EMAIL", "loadtest@example.com")
PASSWORD = os.getenv("LT_PASSWORD", "loadtest-password-123")  # noqa: S105


class LoginUser(HttpUser):
    # Без пауз между запросами: см. модульный докстринг.
    wait_time = constant(0)

    def on_start(self):
        # Запрещаем клиенту брать прокси из окружения. На Windows системный прокси
        # (VPN) лежит в реестре и подхватывается автоматически — тогда трафик на
        # 127.0.0.1 уходит наружу, и вместо стоимости bcrypt мы меряем латентность
        # прокси. requests список исключений реестра обычно учитывает и localhost
        # пропускает мимо, но в замере это не то, на что стоит полагаться.
        # Тот же случай с httpx уже ловился в seed_user.py — там он давал 503.
        self.client.trust_env = False

    @task
    def login(self):
        with self.client.post(
            "/auth/login",
            json={"email": EMAIL, "password": PASSWORD},
            name="POST /auth/login",
            catch_response=True,
        ) as resp:
            if resp.status_code != 200:
                # Явно валим прогон: молчаливые 4xx/5xx превратили бы замер
                # стоимости bcrypt в замер стоимости отказа.
                resp.failure(f"ожидали 200, получили {resp.status_code}: {resp.text[:200]}")
